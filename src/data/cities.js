// Beyond this distance the Habous table is not used and times are calculated instead.
const MAX_DISTANCE_KM = 50;

const distanceKm = (lat1, lng1, lat2, lng2) => {
    const rad = Math.PI / 180;
    const dLat = (lat2 - lat1) * rad;
    const dLng = (lng2 - lng1) * rad;
    const a = Math.sin(dLat / 2) ** 2 +
        Math.cos(lat1 * rad) * Math.cos(lat2 * rad) * Math.sin(dLng / 2) ** 2;
    return 6371 * 2 * Math.asin(Math.sqrt(a));
};

/** Nearest Habous city to a position, or null when none is within MAX_DISTANCE_KM (e.g. abroad). */
export const findNearestCity = (lat, lng) => {
    if (lat === "" || lng === "" || lat == null || lng == null) return null;
    let best = null;
    let bestDist = Infinity;
    for (const city of habousCities) {
        const d = distanceKm(lat, lng, city.lat, city.lng);
        if (d < bestDist) { best = city; bestDist = d; }
    }
    return bestDist <= MAX_DISTANCE_KM ? best : null;
};
